const FYS = [2021, 2022, 2023, 2024, 2025, 2026];

function build(co) {
  const rnd = mulberry32(hash(co.t));
  const jit = (amp) => 1 + (rnd() - 0.5) * 2 * amp;
  const rows = [];
  let rev = co.rev0, eq = null, prevDebt = null, prevNwc = null;
  const annual = [];
  FYS.forEach((fy, i) => {
    if (i > 0) rev = rev * (1 + co.g[i - 1] * jit(0.08));
    const revenue = rev;
    const ebitda = revenue * co.m[i] * jit(0.01);
    const dep = revenue * co.dep * jit(0.04);
    if (eq === null) eq = revenue * co.eq0;
    const debtStart = prevDebt ?? eq * co.de[0];
    const interest = (prevDebt ?? debtStart) * co.rate * jit(0.05);
    const pbt = ebitda - dep - interest;
    const taxRate = 0.25 * jit(0.05);
    const tax = Math.max(0, pbt) * taxRate;
    const np = pbt - tax;
    if (i > 0) eq = eq + np * (1 - co.payout);
    const debt = eq * co.de[i];
    const otherLiab = revenue * 0.22;
    const totalAssets = eq + debt + otherLiab;
    const cash = totalAssets * co.cashPct * jit(0.05);
    const nwc = revenue * 0.1;
    const currentAssets = cash + revenue * 0.17;
    const currentLiab = revenue * 0.16 + debt * 0.05;
    const capex = revenue * co.capex * jit(0.08);
    const dNwc = prevNwc === null ? nwc * 0.15 : nwc - prevNwc;
    const cfo = np + dep - dNwc;
    const cfi = -capex - revenue * 0.008;
    const cff = (prevDebt === null ? 0 : debt - prevDebt) - np * co.payout - interest * 0.2;
    prevDebt = debt; prevNwc = nwc;
    const eps = np / co.shares;
    annual.push({ fy, revenue, ebitda, dep, interest, pbt, tax, np, eps, totalAssets, eq, debt, cash, currentAssets, currentLiab, cfo, capex, cfi, cff });
  });

  annual.forEach((a, i) => {
    const isLast = i === annual.length - 1;
    const row = {
      ticker: co.t, company_name: co.n, exchange: "NSE", sector: co.s,
      period_type: "annual", fiscal_year: `FY${a.fy}`, quarter: "", period_end: `${a.fy}-03-31`,
      currency: "INR", unit: "INR_CRORE",
      revenue: r1(a.revenue), ebitda: r1(a.ebitda), depreciation: r1(a.dep), interest_expense: r1(a.interest),
      pbt: r1(a.pbt), tax: r1(a.tax), net_profit: r1(a.np), eps: r2(a.eps), shares_outstanding_cr: co.shares,
      total_assets: r1(a.totalAssets), total_equity: r1(a.eq), total_debt: r1(a.debt), cash: r1(a.cash),
      current_assets: r1(a.currentAssets), current_liabilities: r1(a.currentLiab),
      cfo: r1(a.cfo), capex: r1(a.capex), cfi: r1(a.cfi), cff: r1(a.cff),
      share_price: isLast ? r2(co.pe * a.eps * jit(0.12)) : "",
      price_date: isLast ? "2026-03-31" : "",
      source: SOURCE, source_url: "", last_updated: LAST_UPDATED, restated: "false", notes: "",
    };
    // Deliberate gaps / restatement so the missing-data and restated UI can be seen in the demo.
    if (co.t === "DEMO-KIT" && a.fy === 2021) { row.cfo = ""; row.capex = ""; row.cfi = ""; row.cff = ""; row.notes = "Cash-flow statement intentionally left blank in demo to show missing-data handling."; }
    if (co.t === "DEMO-GPU" && a.fy === 2022) { row.current_assets = ""; row.current_liabilities = ""; row.notes = "Current assets/liabilities intentionally blank in demo."; }
    if (co.t === "DEMO-NSW" && a.fy === 2023) { row.restated = "true"; row.notes = "Illustrative restatement flag (e.g. after a hypothetical business transfer). Figures are synthetic."; }
    rows.push(row);
  });

  // Quarterly income-statement data for FY2025 and FY2026 (balance sheet / cash flow left blank on purpose).
  const qEnds = { 1: "06-30", 2: "09-30", 3: "12-31", 4: "03-31" };
  [4, 5].forEach((ai) => {
    const a = annual[ai];
    const w = [0.235, 0.245, 0.255, 0.265].map((x) => x * jit(0.02));
    const sw = w.reduce((s, x) => s + x, 0);
    for (let q = 1; q <= 4; q++) {
      const f = w[q - 1] / sw;
      const mj = jit(0.02);
      const rev = a.revenue * f;
      const ebitda = a.ebitda * f * mj;
      const dep = a.dep * 0.25;
      const interest = a.interest * 0.25;
      const pbt = ebitda - dep - interest;
      const tax = Math.max(0, pbt) * 0.25;
      const np = pbt - tax;
      const endYear = q === 4 ? a.fy : a.fy - 1;
      rows.push({
        ticker: co.t, company_name: co.n, exchange: "NSE", sector: co.s,
        period_type: "quarterly", fiscal_year: `FY${a.fy}`, quarter: `Q${q}`, period_end: `${endYear}-${qEnds[q]}`,
        currency: "INR", unit: "INR_CRORE",
        revenue: r1(rev), ebitda: r1(ebitda), depreciation: r1(dep), interest_expense: r1(interest),
        pbt: r1(pbt), tax: r1(tax), net_profit: r1(np), eps: r2(np / co.shares), shares_outstanding_cr: co.shares,
        total_assets: "", total_equity: "", total_debt: "", cash: "", current_assets: "", current_liabilities: "",
        cfo: "", capex: "", cfi: "", cff: "", share_price: "", price_date: "",
        source: SOURCE, source_url: "", last_updated: LAST_UPDATED, restated: "false", notes: "",
      });
    }
  });
  return rows;
}

const esc = (v) => {
  const s = v === undefined || v === null ? "" : String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const toCsv = (rows) => [COLS.join(","), ...rows.map((r) => COLS.map((c) => esc(r[c])).join(","))].join("\n") + "\n";

const demoRows = COMPANIES.flatMap(build);
const demoCsv = toCsv(demoRows);
